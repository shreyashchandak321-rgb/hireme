import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {stripTypeScriptTypes} from 'node:module';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'careerpilot-test-'));
process.env.CAREERPILOT_DATA_DIR=root;
const base=new URL('../apps/web/app/careerpilot/',import.meta.url);
let source=fs.readFileSync(new URL('runtime.ts',base),'utf8').replace("import 'server-only';",'').replace("import {schema} from './schema';",fs.readFileSync(new URL('schema.ts',base),'utf8').replace('export const','const'));
const js=stripTypeScriptTypes(source,{mode:'transform'});
const {env}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
for(const owner of ['alice','bob'])await env.DB.prepare('INSERT INTO records VALUES(?,?,?,?,?)').bind(owner+':profile:main',owner,'profile',JSON.stringify({name:owner}),1).run();
assert.equal((await env.DB.prepare('SELECT data FROM records WHERE owner=?').bind('alice').all()).results.length,1);
assert.equal(await env.DB.prepare('SELECT data FROM records WHERE id=? AND owner=?').bind('bob:profile:main','alice').first(),null);
await assert.rejects(env.DB.batch([env.DB.prepare('INSERT INTO records VALUES(?,?,?,?,?)').bind('rollback','alice','test','{}',1),env.DB.prepare('INSERT INTO records VALUES(?,?,?,?,?)').bind('alice:profile:main','alice','test','{}',1)]));
assert.equal(await env.DB.prepare('SELECT id FROM records WHERE id=?').bind('rollback').first(),null);
await env.BUCKET.put('alice/resume',new Uint8Array([1,2,3]),{httpMetadata:{contentType:'application/pdf'}});
assert.deepEqual(Array.from((await env.BUCKET.get('alice/resume')).body),[1,2,3]);assert.equal(await env.BUCKET.get('bob/resume'),null);
console.log('PASS owner-filtered reads, transaction rollback, file roundtrip and separate object keys');
fs.rmSync(root,{recursive:true,force:true});
