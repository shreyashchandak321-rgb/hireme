"""Compile the finite server query set into a service-only Postgres RPC registry.
Run after changing SQL in API routes; no arbitrary client SQL is accepted.
"""
from pathlib import Path
import re, json, hashlib
root=Path(__file__).resolve().parents[1]
queries=set()
for p in (root/'apps/web/app').rglob('*.ts'):
 if p.name=='runtime.ts': continue
 for m in re.finditer(r'\.prepare\((\x27[^\x27\n]*\x27|"[^"\n]*")\)',p.read_text()):
  queries.add(m.group(1)[1:-1])

def args(s):
 out=[]; start=0; depth=0; quoted=False
 for i,c in enumerate(s):
  if c=="'": quoted=not quoted
  if not quoted:
   if c=='(': depth+=1
   if c==')': depth-=1
   if c==',' and depth==0: out.append(s[start:i].strip()); start=i+1
 return out+[s[start:].strip()]
def convert(s):
 pat=re.compile(r'\b(json_extract|json_patch|json_set|json_insert|json)\(')
 while m:=pat.search(s):
  depth=1; quote=False; end=m.end()
  while depth:
   c=s[end]
   if c=="'":quote=not quote
   if not quote:
    if c=='(':depth+=1
    if c==')':depth-=1
   end+=1
  a=[convert(x) for x in args(s[m.end():end-1])]; fn=m.group(1)
  if fn=='json_extract':
   key=a[1][3:-1]; expr=f"({a[0]}::jsonb->>'{key}')"
   if key in ['seen']:expr=f'({expr})::bigint'
   if key in ['profileParse','roleSuggestions','configured','fastApply']:expr=f"CASE {expr} WHEN 'true' THEN 1 WHEN '1' THEN 1 WHEN 'false' THEN 0 WHEN '0' THEN 0 ELSE NULL END"
  elif fn=='json_patch':expr=f'careerpilot.merge_patch({a[0]}, {a[1]})'
  elif fn=='json':expr=f'({a[0]})::jsonb'
  elif fn=='json_insert':
   assert a[1]=="'$.events[#]'"
   expr=f"jsonb_set(({a[0]})::jsonb, '{{events}}', COALESCE(({a[0]})::jsonb->'events', '[]'::jsonb) || jsonb_build_array({a[2]}), true)::text"
   # This duplicates bind placeholders in the patch; instead call a helper once.
   expr=f'careerpilot.append_event({a[0]}, {a[2]})'
  elif fn=='json_set':
   expr=f'({a[0]})::jsonb'
   for i in range(1,len(a),2):
    key=a[i][3:-1]; v=a[i+1]
    if not v.endswith('::jsonb'):v=f"COALESCE(to_jsonb(({v})::text), 'null'::jsonb)"
    expr=f"jsonb_set({expr}, '{{{key}}}', {v}, true)"
   expr=f'({expr})::text'
  s=s[:m.start()]+expr+s[end:]
 return s
registry=[]; rows=[]
for q in sorted(queries):
 pg=convert(q); assert pg.count('?')==q.count('?'),q
 key=hashlib.sha256(q.encode()).hexdigest()
 returning=pg.startswith('SELECT') or ' RETURNING ' in pg
 if not returning:pg+=' RETURNING 1 AS affected'
 registry.append((q,key))
 rows.append("('%s', %s, %d)"%(key,"'"+pg.replace("'","''")+"'",q.count('?')))
p=root/'apps/web/app/careerpilot/query-registry.ts'
p.write_text('// Generated by scripts/generate-careerpilot-db.py. Server-only query identifiers.\nexport const queryIds: Record<string, string> = '+json.dumps(dict(registry),indent=2)+';\n')
base=(root/'scripts/careerpilot-schema.sql').read_text()
base+='\nINSERT INTO careerpilot.queries(id, sql, arity) VALUES\n'+',\n'.join(rows)+'\nON CONFLICT (id) DO UPDATE SET sql=excluded.sql, arity=excluded.arity;\n'
base+="\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
(root/'apps/web/supabase/migrations/20261022000000_careerpilot_cloud.sql').write_text(base)
print(f'Compiled {len(rows)} queries')
